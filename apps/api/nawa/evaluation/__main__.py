def _register_models() -> None:
    """Load every ORM model so foreign keys (knowledge -> workspaces) resolve in this process.

    Dynamic on purpose: evaluation must not import another module's models statically.
    """
    for module in ("nawa.workspace.models", "nawa.knowledge.models"):
        importlib.import_module(module)


def _repo_root() -> Path:
    """The checkout root (has an `evals` folder); inside the image it is overridden by env vars."""
    for parent in Path(__file__).resolve().parents:
        if (parent / "evals").is_dir():
            return parent
    return Path.cwd()


def format_summary(summary: EvalRunSummary) -> str:
    lines = [f"run {summary.run_id}  config {summary.config['name']}", ""]
    for key, (target, op) in TARGETS.items():
        value = summary.metrics.get(key, 0.0)
        ok = value >= target if op == ">=" else value < target
        shown = f"{value:.0f} ms" if key.endswith("_ms") else f"{value:.3f}"
        lines.append(
            f"  {key:22} {shown:>10}   target {op} {target:g}   {'ok' if ok else 'BELOW TARGET'}"
        )
    lines += ["", "  " + ", ".join(f"{k}={v}" for k, v in sorted(summary.counts.items()))]
    if summary.counts.get("errors") or summary.counts.get("judge_errors"):
        lines.append("  NOTE: items with errors are excluded from the averages above.")
    return "\n".join(lines)


async def _run(args: argparse.Namespace) -> int:
    settings = get_settings()
    root = _repo_root()
    evals_dir = Path(os.environ.get("EVALS_DIR", root / "evals"))
    docs_dir = Path(os.environ.get("DEMO_DOCS_DIR", root / "seed" / "noesantara_docs"))
    try:
        config = RunConfig.load(args.config, evals_dir / "configs")
    except EvalConfigError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    problem = check_preconditions(config, settings)
    if problem:
        print(f"error: {problem}", file=sys.stderr)
        return 2
    engine = create_async_engine(settings.database_url)
    try:
        summary = await run_evaluation(
            config,
            settings=settings,
            client=LiteLLMClient(),
            maker=async_sessionmaker(engine, expire_on_commit=False),
            docs_dir=docs_dir,
            golden_path=evals_dir / "golden.yaml",
            manifest_path=docs_dir / "MANIFEST.yaml",
            upload_dir=Path(settings.upload_dir) / "eval",
            limit=args.limit,
            progress=lambda message: print(message, flush=True),
        )
    except EvalConfigError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    finally:
        await engine.dispose()
    print(format_summary(summary))
    return 0


LIMITATIONS = (
    "The judge is one LLM (DeepSeek) that also sees synthetic Indonesian text; its verdicts are "
    "not human-verified, and judge errors are excluded from the averages.",
    "The golden set has 75 items (60 answerable, 10 unanswerable, 5 injection); one item moves "
    "a rate by 1.7, 10 and 20 points respectively, so small gaps between arms are within noise.",
    "All documents are synthetic and generated by one process; real company documents are messier.",
    "Generation uses provider-default sampling and no seed, so reruns differ slightly; latency "
    "depends on the host and on API load at the time.",
)


def _hardware() -> str:
    mem = ""
    try:
        with open("/proc/meminfo", encoding="utf-8") as f:
            kb = int(f.readline().split()[1])
        mem = f", {kb / 1024 / 1024:.0f} GiB RAM"
    except (OSError, ValueError, IndexError):
        pass
    return f"{platform.platform()}, {os.cpu_count()} CPU threads{mem}"


def _paths(args: argparse.Namespace) -> tuple[Path, Path, Path]:
    root = _repo_root()
    evals_dir = Path(os.environ.get("EVALS_DIR", root / "evals"))
    docs_dir = Path(os.environ.get("DEMO_DOCS_DIR", root / "seed" / "noesantara_docs"))
    results_dir = Path(args.results_dir) if args.results_dir else evals_dir / "results"
    return evals_dir, docs_dir, results_dir


async def _experiments(args: argparse.Namespace) -> int:
    settings = get_settings()
    evals_dir, docs_dir, results_dir = _paths(args)
    known = load_experiments(evals_dir / "experiments.yaml")
    wanted = [e for e in known if args.name in ("all", e.name)]
    if not wanted:
        print(
            f"error: unknown experiment {args.name!r}; known: {[e.name for e in known]}",
            file=sys.stderr,
        )
        return 2
    if settings.offline_mode:
        print("error: OFFLINE_MODE=true: evaluation refuses to run offline.", file=sys.stderr)
        return 2
    commit = git_commit(_repo_root())
    engine = create_async_engine(settings.database_url)
    maker = async_sessionmaker(engine, expire_on_commit=False)
    client = LiteLLMClient()

    async def run_arm(config: RunConfig) -> EvalRunSummary:
        bad = check_preconditions(config, settings)
        if bad:
            raise EvalConfigError(bad)
        return await run_evaluation(
            config,
            settings=settings,
            client=client,
            maker=maker,
            docs_dir=docs_dir,
            golden_path=evals_dir / "golden.yaml",
            manifest_path=docs_dir / "MANIFEST.yaml",
            upload_dir=Path(settings.upload_dir) / "eval",
            limit=args.limit,
            progress=lambda message: print(message, flush=True),
        )

    try:
        for experiment in wanted:
            print(f"== experiment {experiment.name} ({len(experiment.arms)} arms)", flush=True)
            result = await run_experiment(
                experiment,
                run_arm,
                env=os.environ,
                default_models={
                    "generator": settings.llm_model,
                    "embedding": settings.embedding_model,
                    "judge": settings.llm_model,
                },
                commit=commit,
            )
            print(f"saved {save_result(result, results_dir)}", flush=True)
            for arm in result.arms:
                print(f"  {arm.name}: {arm.status} {arm.reason}".rstrip(), flush=True)
    finally:
        await engine.dispose()
    return 0


async def _report(args: argparse.Namespace) -> int:
    settings = get_settings()
    evals_dir, docs_dir, results_dir = _paths(args)
    files = sorted(results_dir.glob("*.json"))
    if not files:
        print(f"error: no results in {results_dir}; run `experiments` first", file=sys.stderr)
        return 2
    order = [e.name for e in load_experiments(evals_dir / "experiments.yaml")]
    loaded = [load_result(f) for f in files]
    results: list[ExperimentResult] = sorted(
        loaded, key=lambda r: order.index(r.name) if r.name in order else len(order)
    )
    arms = {a.name: a for r in results for a in r.arms}
    golden = load_golden(evals_dir / "golden.yaml", docs_dir / "MANIFEST.yaml")
    sweep, chosen = [], None
    calib = arms.get(args.calibration_arm)
    if calib is not None and calib.status == "ok" and calib.run_id:
        engine = create_async_engine(settings.database_url)
        try:
            samples = await load_samples(
                async_sessionmaker(engine, expire_on_commit=False),
                calib.run_id,
                {g.id: g.kind for g in golden},
            )
        finally:
            await engine.dispose()
        sweep = sweep_threshold(samples)
        chosen = pick_threshold(sweep, min_answerable_recall=args.min_answerable_recall)
    kinds = [g.kind for g in golden]
    first = next(iter(arms.values()))
    setup = {
        "Date": date.today().isoformat(),
        "Commit": first.git_commit,
        "Hardware": _hardware(),
        "Dataset": f"{len(golden)} items: "
        + ", ".join(f"{kinds.count(k)} {k}" for k in ("answerable", "unanswerable", "injection")),
        "Documents": "synthetic demo set (seed/noesantara_docs)",
        "Models (default)": ", ".join(f"{k}: {v}" for k, v in first.models.items() if v),
        "litellm": first.litellm_version,
    }
    out = Path(args.output) if args.output else _repo_root() / "docs" / "evaluation-report.md"
    existing = out.read_text(encoding="utf-8") if out.is_file() else ""
    charts = render_charts(results)
    markdown = render(
        setup=setup,
        experiments=results,
        sweep=sweep,
        chosen=chosen,
        min_answerable_recall=args.min_answerable_recall,
        final=arms.get(args.final_arm),
        limitations=LIMITATIONS,
        analysis=extract_analysis(existing),
        charts=list(charts),
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(markdown, encoding="utf-8")
    images = out.parent / "images"
    images.mkdir(exist_ok=True)
    for name, svg in charts.items():
        (images / name).write_text(svg, encoding="utf-8")
    print(f"wrote {out} and {len(charts)} charts")
    return 0


def main(argv: list[str] | None = None) -> int:
    _register_models()
    parser = argparse.ArgumentParser(prog="python -m nawa.evaluation")
    sub = parser.add_subparsers(dest="command", required=True)
    run = sub.add_parser("run", help="run the golden dataset against one configuration")
    run.add_argument("--config", default="default", help="config name (evals/configs) or YAML path")
    run.add_argument("--limit", type=int, default=None, help="evaluate only N items (all kinds)")
    exp = sub.add_parser("experiments", help="run one experiment (or `all`), saving JSON results")
    exp.add_argument("--name", default="all")
    exp.add_argument("--limit", type=int, default=None)
    exp.add_argument("--results-dir", default=None)
    rep = sub.add_parser("report", help="render docs/evaluation-report.md from saved results")
    rep.add_argument("--results-dir", default=None)
    rep.add_argument("--output", default=None)
    rep.add_argument("--calibration-arm", default="retrieval-hybrid")
    rep.add_argument("--final-arm", default="chunk-heading")
    rep.add_argument("--min-answerable-recall", type=float, default=0.95)
    args = parser.parse_args(argv)
    handler = {"run": _run, "experiments": _experiments, "report": _report}[args.command]
    return asyncio.run(handler(args))


if __name__ == "__main__":
    raise SystemExit(main())
